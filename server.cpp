int main()
{
    // get server/host ip
    struct addrinfo hints{};
    hints.ai_family = AF_INET;
    hints.ai_socktype = SOCK_STREAM;
    hints.ai_protocol = 0;
    struct addrinfo *res;
    getaddrinfo("127.0.0.1", "1234", &hints, &res);
    char ip[INET_ADDRSTRLEN];
    // inet_ntop(AF_INET, reinterpret_cast<sockaddr_in *>(res->ai_addr)->sin_addr, ip, INET_ADDRSTRLEN);
    inet_ntop(AF_INET, &reinterpret_cast<sockaddr_in *>(res->ai_addr)->sin_addr, ip, INET_ADDRSTRLEN);

    cout << ip << endl;

    // socket
    int fd = socket(hints.ai_family, hints.ai_socktype, hints.ai_protocol);
    if (fd < 0)
    {
        die("Socket failure");
    }

    // Allow binding to the port even if it is in TIME_WAIT
    int val = 1;
    if (setsockopt(fd, SOL_SOCKET, SO_REUSEADDR, &val, sizeof(val)) < 0)
    {
        die("setsockopt failure");
    }

    // bind fd to socket
    if (bind(fd, res->ai_addr, res->ai_addrlen))
    {
        die("Bind failure");
    }

    if (listen(fd, SOMAXCONN))
    {
        die("Listen failure");
    }

    while (true)
    {
        int acceptFd = accept(fd, nullptr, nullptr);

        if (acceptFd < 0)
        {
            die("Accept failure");
            break;
        }

        int maxBytes = 5;
        char s[maxBytes];
        int bytesRed = -2;
        do
        {
            bytesRed = read(acceptFd, s, maxBytes);
            if (bytesRed > 0 && bytesRed < maxBytes)
            {
                s[bytesRed] = '\0';
                cout << bytesRed << ": " << s << endl;
            }
            if (bytesRed == 0)
            {
                break;
            }
            cout << "About to write!" << endl;
            const char *reply = "Cops eat dick!";

            int bytesWrote = write(acceptFd, reply, strlen(reply) * sizeof(char));
        } while (bytesRed > 0);
    }
};
